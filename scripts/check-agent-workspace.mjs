import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createServer } from 'node:http'
import { pathToFileURL } from 'node:url'
import { join } from 'node:path'
import { fixture } from './workshop-fixture.mjs'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
const bundle = await readFile(new URL('../dist/frontend.js', import.meta.url))
const backend = await readFile(new URL('../dist/backend.js', import.meta.url))
const server = createServer((req, res) => { res.setHeader('Content-Type', req.url.endsWith('.js') ? 'text/javascript' : 'text/html'); res.end(req.url === '/frontend.js' ? bundle : req.url === '/backend.js' ? backend : fixture) })
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const browser = await chromium.launch({ headless: true })
try {
  for (const width of [1440, 390]) {
    const height = width < 900 ? 844 : 900
    const page = await browser.newPage({ viewport: { width, height } })
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(`http://127.0.0.1:${server.address().port}`)
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    await page.getByRole('button', { name: 'Agent', exact: true }).click()
    const workspace = page.getByRole('region', { name: 'Agent workspace', exact: true })
    // One compact composer action; disabled until there is both a connection and text.
    const action = workspace.locator('.workshop-agent-composer button')
    assert.equal(await action.count(), 1)
    assert.equal(await action.getAttribute('aria-label'), 'Send')
    assert.equal(await action.isDisabled(), true)
    assert.equal(await workspace.locator('svg').evaluateAll(nodes => nodes.every(node => node.getAttribute('aria-hidden') === 'true')), true)
    const nav = workspace.getByRole('complementary', { name: 'Agent prompts', exact: true })
    const openNavigation = async () => {
      if (!(await nav.isVisible())) await workspace.getByRole('button', { name: 'Open agent prompts', exact: true }).click()
    }
    await openNavigation()
    assert.equal(await workspace.getByRole('button', { name: 'Close agent prompts', exact: true }).getAttribute('aria-expanded'), 'true')
    await nav.locator('[data-block-id="two"]').click()
    assert.equal(await workspace.getByLabel('Draft content', { exact: true }).inputValue(), '{{var::missing_two}}')
    await openNavigation()
    await nav.getByLabel('Search prompts', { exact: true }).fill('one')
    assert.equal(await nav.locator('[data-block-id="two"]').count(), 0)
    await nav.getByLabel('Search prompts', { exact: true }).fill('')
    await nav.locator('[data-block-id="one"]').click()
    await workspace.getByLabel('Draft content', { exact: true }).fill('manual draft')
    await openNavigation()
    await nav.locator('[data-block-id="two"]').click()
    await openNavigation()
    await nav.locator('[data-block-id="one"]').click()
    assert.equal(await workspace.getByLabel('Draft content', { exact: true }).inputValue(), 'manual draft')
    await openNavigation()
    await nav.getByRole('button', { name: 'Collapse agent prompt sidebar', exact: true }).click()
    assert.equal(await nav.isVisible(), false)
    assert.equal(await workspace.getByRole('button', { name: 'Open agent prompts', exact: true }).getAttribute('aria-expanded'), 'false')
    assert.equal(await workspace.getByRole('button', { name: 'Open agent prompts', exact: true }).evaluate(el => el === document.activeElement), true)
    assert.equal(await page.evaluate(() => window.writes), 0)
    assert.equal(await page.evaluate(() => window.snapshot().blocks[0].content), '{{var::missing_one}}')
    // The existing preview remains the one and only instance after reparenting.
    assert.equal(await workspace.locator('.workshop-preview').count(), 1)
    const preview = await workspace.locator('.workshop-preview').boundingBox()
    assert.ok(preview.width > 0 && preview.x >= 0 && preview.x + preview.width <= width && preview.y + preview.height <= height)
    for (const name of ['Leave agent', 'Apply drafts', 'Close Workshop']) {
      const bounds = await page.getByRole('button', { name, exact: true }).boundingBox()
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width && bounds.y >= (width < 900 ? 54 : 0), name)
    }
    await page.getByRole('button', { name: 'Leave agent', exact: true }).click()
    let exit = page.getByRole('dialog', { name: 'Leave agent mode?', exact: true })
    assert.equal(await exit.getByRole('button', { name: 'Stay', exact: true }).evaluate(el => el === document.activeElement), true)
    await page.keyboard.press('Escape')
    assert.equal(await exit.count(), 0)
    assert.equal(await workspace.isVisible(), true)
    await page.getByRole('button', { name: 'Close Workshop', exact: true }).click()
    await exit.getByRole('button', { name: 'Keep drafts and leave', exact: true }).click()
    assert.equal(await workspace.count(), 0)
    assert.equal(await page.getByRole('button', { name: 'Agent', exact: true }).evaluate(el => el === document.activeElement), true)
    assert.equal(await page.locator('.workshop-center > .workshop-preview').count(), 1)
    // Confirmation remains mandatory after keeping drafts and returning to Workshop.
    await page.getByRole('button', { name: 'Apply drafts', exact: true }).click()
    const apply = page.getByRole('dialog', { name: 'Apply local agent drafts?', exact: true })
    await apply.getByRole('button', { name: 'Keep editing', exact: true }).click()
    assert.equal(await page.evaluate(() => window.writes), 0)
    // Agent drafts can also be applied from the second-modal reviewer; Escape
    // dismisses only the native confirmation and leaves both host surfaces open.
    if (width < 900) await page.getByRole('button', { name: 'Open variables', exact: true }).click()
    await page.getByRole('button', { name: 'Review issues', exact: true }).click()
    const review = page.locator('.workshop-review')
    await review.getByRole('button', { name: 'Apply', exact: true }).click()
    await apply.waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await apply.count(), 0)
    assert.equal(await review.count(), 1)
    assert.equal(await page.locator('.workshop-shell').count(), 1)
    await review.getByRole('button', { name: 'Close', exact: true }).click()
    await page.getByRole('button', { name: 'Agent', exact: true }).click()
    assert.equal(await workspace.getByLabel('Draft content', { exact: true }).inputValue(), 'manual draft')
    const instruction = workspace.getByLabel('Ask the preset assistant', { exact: true })
    await instruction.fill('Fix one')
    await instruction.press('Shift+Enter')
    assert.equal(await instruction.inputValue(), 'Fix one\n')
    assert.equal(await page.evaluate(() => window.agentRequests || 0), 0)
    await instruction.press('Enter')
    await workspace.getByText('Finished. Review local drafts and preview before Apply.', { exact: true }).waitFor()
    assert.equal(await workspace.getByLabel('Draft content', { exact: true }).inputValue(), 'agent fixed')
    assert.equal(await page.evaluate(() => window.writes), 0)
    assert.equal(await page.evaluate(() => window.remoteToolCalls || 0), 0)
    await page.getByRole('button', { name: 'Apply drafts', exact: true }).click()
    await apply.getByRole('button', { name: 'Apply drafts', exact: true }).click()
    await page.locator('[data-action="apply-drafts"]').waitFor({ state: 'hidden' })
    assert.equal(await page.evaluate(() => window.snapshot().blocks[0].content), 'agent fixed')
    assert.equal(await page.evaluate(() => window.writes), 1)
    assert.ok(await page.evaluate(() => Object.keys(localStorage).some(key => key.startsWith('backup:'))))
    // Explicit MCP selection still never executes file tools remotely.
    await workspace.getByLabel('PresetTools compatibility', { exact: true }).selectOption('tools')
    await workspace.getByLabel('Ask the preset assistant', { exact: true }).fill('Inspect with compatibility')
    await workspace.getByRole('button', { name: 'Send', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[data-agent="send"]').getAttribute('aria-label') === 'Send')
    assert.equal(await page.evaluate(() => window.remoteToolCalls || 0), 0)
    // Stop, then deliver a late provider result: it must not stage anything.
    await page.evaluate(() => { window.generationDelay = true })
    await workspace.getByLabel('Ask the preset assistant', { exact: true }).fill('Delayed edit')
    await workspace.getByRole('button', { name: 'Send', exact: true }).click()
    await page.waitForFunction(() => !!window.releaseGeneration)
    assert.equal(await action.count(), 1)
    assert.equal(await action.getAttribute('aria-label'), 'Stop')
    assert.equal(await action.isDisabled(), false)
    const requestsBeforeStop = await page.evaluate(() => window.agentRequests)
    await workspace.getByLabel('Ask the preset assistant', { exact: true }).fill('Keep this next instruction')
    await workspace.getByRole('button', { name: 'Stop', exact: true }).click()
    assert.equal(await action.getAttribute('aria-label'), 'Send')
    assert.equal(await action.isDisabled(), false)
    assert.equal(await page.evaluate(() => window.agentRequests), requestsBeforeStop)
    assert.equal(await workspace.getByLabel('Ask the preset assistant', { exact: true }).inputValue(), 'Keep this next instruction')
    await page.evaluate(() => { window.generationDelay = false; window.releaseGeneration() })
    assert.equal(await workspace.getByLabel('Draft content', { exact: true }).inputValue(), 'agent fixed')
    // External changes are never overwritten by a stale result or manual edit.
    await workspace.getByLabel('Draft content', { exact: true }).fill('before stale run')
    await page.evaluate(() => { window.generationDelay = true; window.releaseGeneration = null })
    await workspace.getByLabel('Ask the preset assistant', { exact: true }).fill('Stale edit')
    await workspace.getByRole('button', { name: 'Send', exact: true }).click()
    await page.waitForFunction(() => !!window.releaseGeneration)
    await page.evaluate(() => window.external('other'))
    await page.evaluate(() => { window.generationDelay = false; window.releaseGeneration() })
    await workspace.getByText(/host preset changed during agent mode/).waitFor()
    assert.equal(await workspace.getByLabel('Draft content', { exact: true }).inputValue(), 'before stale run')
    await workspace.getByLabel('Draft content', { exact: true }).fill('stale manual edit')
    await workspace.getByText(/host preset changed during agent mode/).waitFor()
    await page.getByRole('button', { name: 'Leave agent', exact: true }).click()
    await exit.getByRole('button', { name: 'Discard drafts and leave', exact: true }).click()
    await page.getByRole('button', { name: 'Agent', exact: true }).click()
    assert.equal(await workspace.getByLabel('Draft content', { exact: true }).inputValue(), 'agent fixed')
    if (width < 900) {
      const content = await workspace.getByLabel('Draft content', { exact: true }).boundingBox()
      const connection = await workspace.getByLabel('Lumi connection', { exact: true }).boundingBox()
      assert.ok(connection.y >= content.y + content.height, 'mobile editor and assistant must not overlap')
      const hide = await workspace.getByRole('button', { name: 'Hide', exact: true }).boundingBox()
      assert.ok(hide.x + hide.width <= width, 'mobile preview controls must fit')
    }
    const composer = await workspace.locator('.workshop-agent-composer').boundingBox()
    const send = await action.boundingBox()
    const input = await workspace.getByLabel('Ask the preset assistant', { exact: true }).boundingBox()
    assert.ok(send.x > input.x && send.x + send.width < composer.x + composer.width && composer.x > 0 && composer.x + composer.width < width, 'composer is inset with the action on the right')
    assert.ok(send.y + send.height <= composer.y + composer.height, 'action remains inside the composer')
    if (process.env.SANDBOX_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.SANDBOX_SCREENSHOT_DIR, `workshop-agent-${width}.png`) })
    // Disable/unload during generation and an open exit confirmation, then remount.
    await page.evaluate(() => { window.generationDelay = true; window.releaseGeneration = null })
    await workspace.getByLabel('Ask the preset assistant', { exact: true }).fill('Unload during generation')
    await workspace.getByRole('button', { name: 'Send', exact: true }).click()
    await page.waitForFunction(() => !!window.releaseGeneration)
    await page.getByRole('button', { name: 'Leave agent', exact: true }).click()
    await page.evaluate(() => { window.disposeWorkshop(); window.generationDelay = false; window.releaseGeneration(); window.disposeWorkshop = window.mountWorkshop() })
    assert.equal(await workspace.count(), 0)
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    await page.getByRole('button', { name: 'Agent', exact: true }).click()
    assert.equal(await workspace.getByLabel('Draft content', { exact: true }).inputValue(), 'agent fixed')
    // Unique IDs and an actual role/name keyboard path after remount.
    assert.equal(await page.evaluate(() => { const ids = [...document.querySelectorAll('[id]')].map(el => el.id); return ids.length === new Set(ids).size }), true)
    await page.getByRole('button', { name: 'Leave agent', exact: true }).press('Enter')
    await exit.getByRole('button', { name: 'Keep drafts and leave', exact: true }).press('Enter')
    // Entering agent mode must not rebase an already-conflicting normal draft.
    if (width < 900) await page.getByRole('button', { name: 'Open prompts', exact: true }).click()
    await page.locator('.workshop-row[data-block-id="one"]').click()
    await page.locator('[data-role="editor-mount"]').getByLabel('Native content').fill('conflicting existing draft')
    await page.evaluate(() => window.external('one'))
    await page.getByRole('button', { name: 'Agent', exact: true }).click()
    await page.getByText('Existing local drafts conflict with the host preset. Resolve or discard them before entering agent mode.', { exact: true }).waitFor()
    assert.equal(await workspace.count(), 0)
    assert.equal(await page.evaluate(() => window.writes), 1)
    // Controlled category cascade reuses Workshop's expansion and restores its state on leaving.
    await page.reload()
    await page.evaluate(() => window.addCategories())
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    await page.getByRole('button', { name: 'Agent', exact: true }).click()
    await openNavigation()
    const category = nav.getByRole('button', { name: 'Collapse Fixture category', exact: true })
    assert.equal(await category.getAttribute('aria-expanded'), 'true')
    await category.press('Enter')
    assert.equal(await nav.getByRole('button', { name: 'Expand Fixture category', exact: true }).evaluate(el => el === document.activeElement), true)
    assert.equal(await nav.locator('[data-block-id="one"]').count(), 0)
    await page.getByRole('button', { name: 'Leave agent', exact: true }).click()
    await exit.getByRole('button', { name: 'Keep drafts and leave', exact: true }).click()
    if (width < 900) await page.getByRole('button', { name: 'Open prompts', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Expand Fixture category', exact: true }).getAttribute('aria-expanded'), 'false')
    await page.getByRole('button', { name: 'Agent', exact: true }).click()
    await openNavigation()
    await nav.getByRole('button', { name: 'Expand Fixture category', exact: true }).click()
    await nav.locator('[data-block-id="two"]').click()
    await workspace.getByLabel('Draft content', { exact: true }).fill('Local prompt draft\n\nNavigate categories and keep editing.\nApply only when you are done.')
    if (width < 900) {
      await openNavigation()
      await page.keyboard.press('Escape')
      assert.equal(await nav.isVisible(), false)
      assert.equal(await exit.count(), 0)
    }
    if (process.env.SANDBOX_SCREENSHOT_DIR) {
      await workspace.getByLabel('Ask the preset assistant', { exact: true }).fill('Review the draft and suggest a clearer opening…')
      await page.screenshot({ path: join(process.env.SANDBOX_SCREENSHOT_DIR, `workshop-agent-polish-${width}.png`) })
    }
    assert.deepEqual(errors, [])
    console.log(`PASS agent workspace: manual/AI drafts, confirmation, keep/discard, MCP compatibility, cancel, host conflict and safe-area layout: ${width}px`)
    await page.close()
  }
} finally { await browser.close(); server.close() }
