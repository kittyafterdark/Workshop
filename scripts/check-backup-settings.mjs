import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createServer } from 'node:http'
import { pathToFileURL } from 'node:url'
import { join } from 'node:path'
import { fixture } from './workshop-fixture.mjs'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
const bundle = await readFile(new URL('../dist/frontend.js', import.meta.url))
const backend = await readFile(new URL('../dist/backend.js', import.meta.url))
const server = createServer((req, res) => { res.setHeader('Content-Type', req.url.endsWith('.js') ? 'text/javascript' : 'text/html'); res.end(req.url === '/frontend.js' ? bundle : req.url === '/backend.js' ? backend : fixture) })
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const browser = await chromium.launch({ headless: true })
try {
  for (const width of [1440, 390]) {
    const page = await browser.newPage({ viewport: { width, height: width < 900 ? 844 : 900 } })
    await page.clock.install()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(`http://127.0.0.1:${server.address().port}`)
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    if (width < 900) await page.getByRole('button', { name: 'Open prompts', exact: true }).click()
    await page.locator('.workshop-row[data-block-id="one"]').click()
    const content = page.locator('[data-role="editor-mount"]').getByLabel('Native content')
    await content.fill('Manual baseline')
    const backups = page.getByRole('dialog', { name: 'Preset backups', exact: true })
    const ready = () => backups.getByText('Ready. Restoring stages changes locally; Apply syncs them.', { exact: true }).waitFor()
    const open = async () => { await page.getByRole('button', { name: 'Preset backups', exact: true }).click(); await ready() }
    const settings = backups.getByRole('form', { name: 'Backup settings', exact: true })
    const configure = async () => { await backups.getByRole('button', { name: 'Settings', exact: true }).click(); await settings.waitFor() }
    const saved = async () => { await settings.getByRole('button', { name: 'Save settings', exact: true }).click(); await ready() }
    const stored = () => page.evaluate(() => Object.keys(localStorage).filter(k => k.startsWith('backup:')).map(k => JSON.parse(JSON.parse(localStorage.getItem(k)).text)))
    await open()
    await backups.getByRole('button', { name: 'Create backup', exact: true }).click(); await ready()
    await backups.getByRole('button', { name: 'Create backup', exact: true }).click(); await ready()
    await configure()
    const toggle = settings.getByRole('switch', { name: 'Automatic timed backups', exact: true })
    assert.equal(await toggle.isChecked(), false)
    await toggle.press('Space')
    await settings.getByLabel('Interval in minutes', { exact: true }).fill('1')
    await settings.getByLabel('Maximum backups to keep', { exact: true }).fill('2')
    if (process.env.SANDBOX_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.SANDBOX_SCREENSHOT_DIR, `backup-settings-${width}.png`) })
    await saved()
    assert.equal(await backups.getByRole('button', { name: 'Settings', exact: true }).getAttribute('aria-expanded'), 'false')
    assert.equal(await backups.getByRole('button', { name: 'Settings', exact: true }).evaluate(el => el === document.activeElement), true)
    await backups.getByRole('button', { name: 'Close', exact: true }).click()
    await content.fill('Unsynced timed recovery')
    await page.clock.fastForward(60000)
    await page.waitForFunction(() => Object.keys(localStorage).filter(k => k.startsWith('backup:')).some(k => JSON.parse(JSON.parse(localStorage.getItem(k)).text).kind === 'automatic'))
    let files = await stored()
    assert.equal(files.length, 2)
    assert.ok(files.some(b => b.kind === 'automatic' && b.preset.blocks[0].content === 'Unsynced timed recovery'))
    assert.equal(await page.evaluate(() => window.writes), 0)
    const unchangedPaths = files.map(b => b.path).sort()
    await page.clock.fastForward(60000)
    assert.deepEqual((await stored()).map(b => b.path).sort(), unchangedPaths)
    await content.fill('Second local recovery')
    await page.clock.fastForward(60000)
    await page.waitForFunction(() => Object.keys(localStorage).filter(k => k.startsWith('backup:')).some(k => JSON.parse(JSON.parse(localStorage.getItem(k)).text).preset.blocks[0].content === 'Second local recovery'))
    assert.equal((await stored()).length, 2)
    await open()
    assert.equal(await backups.locator('.workshop-backup-row').count(), 2)
    await configure()
    await settings.getByLabel('Maximum backups to keep', { exact: true }).fill('1')
    await saved()
    assert.equal(await backups.locator('.workshop-backup-row').count(), 1)
    await backups.getByRole('button', { name: 'Close', exact: true }).click()
    await page.evaluate(() => { window.backupFailure = true })
    await content.fill('Failed timed write stays local')
    await page.clock.fastForward(60000)
    await page.waitForFunction(() => document.querySelector('[data-action="backups"]').hasAttribute('data-backup-error'))
    assert.equal((await stored()).length, 1)
    await page.evaluate(() => { window.backupFailure = false })
    await open(); await configure()
    await toggle.press('Space')
    await page.evaluate(() => { window.settingsFailure = true })
    await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
    await backups.getByRole('status').filter({ hasText: /Backup storage is unavailable/ }).waitFor()
    assert.equal(await settings.isVisible(), true)
    await page.evaluate(() => { window.settingsFailure = false })
    await saved()
    await backups.getByRole('button', { name: 'Close', exact: true }).click()
    const paused = (await stored()).map(b => b.path)
    await page.clock.fastForward(120000)
    assert.deepEqual((await stored()).map(b => b.path), paused)
    // Durable settings survive page reload and expiry; no orphan timer survives Workshop close.
    await page.reload()
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    await open(); await configure()
    assert.equal(await toggle.isChecked(), false)
    assert.equal(await settings.getByLabel('Maximum backups to keep', { exact: true }).inputValue(), '1')
    await toggle.press('Space'); await saved()
    await backups.getByRole('button', { name: 'Close', exact: true }).click()
    await page.getByRole('button', { name: 'Close Workshop', exact: true }).click()
    const closedFiles = (await stored()).map(b => b.path)
    await page.clock.fastForward(120000)
    assert.deepEqual((await stored()).map(b => b.path), closedFiles)
    assert.deepEqual(errors, [])
    console.log(`PASS timed backups: local capture, count pruning, unchanged skip, errors, durable settings, keyboard and lifecycle: ${width}px`)
    await page.close()
  }
} finally { await browser.close(); server.close() }
