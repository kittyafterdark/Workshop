import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createServer } from 'node:http'
import { pathToFileURL } from 'node:url'
import { fixture } from './workshop-fixture.mjs'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
const frontend = await readFile(new URL('../dist/frontend.js', import.meta.url))
const backend = await readFile(new URL('../dist/backend.js', import.meta.url))
const fixtureAnchor = 'window.snapshot=()=>structuredClone(preset);'
assert.equal(fixture.split(fixtureAnchor).length, 2)
const managerFixture = fixture.replace(fixtureAnchor, fixtureAnchor + `
window.populateManagerFixture=()=>{preset.blocks=Array.from({length:143},(_,i)=>({...block('large-'+i,'Controlled content'),name:'Prompt '+(i+1)+' — a long title for the organization list'}));};
`)
const server = createServer((req, res) => {
  res.setHeader('Content-Type', req.url.endsWith('.js') ? 'text/javascript; charset=utf-8' : 'text/html; charset=utf-8')
  res.end(req.url === '/frontend.js' ? frontend : req.url === '/backend.js' ? backend : managerFixture)
})
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) })
try {
  for (const width of [1440, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, hasTouch: width < 900 })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const load = async () => {
      await page.goto(`http://127.0.0.1:${server.address().port}`)
      await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    }
    const open = async () => {
      if (width < 900 && !await page.locator('.workshop-shell').evaluate(el => el.classList.contains('mobile-left-open'))) await page.getByRole('button', { name: 'Open prompts', exact: true }).click()
      await page.getByRole('button', { name: 'Manage prompts', exact: true }).press('Enter')
    }
    const dialog = page.getByRole('dialog', { name: 'Manage prompts', exact: true })
    const choose = name => dialog.getByRole('button', { name: `Select ${name}`, exact: true }).click()
    const titles = () => dialog.locator('.workshop-manage-select span').allTextContents()
    const add = async (kind, name, category) => {
      await dialog.getByRole('button', { name: `Add ${kind}`, exact: true }).click()
      await dialog.getByLabel('Title', { exact: true }).fill(name)
      if (kind !== 'category' && category !== undefined) await dialog.getByRole('combobox', { name: 'Category', exact: true }).selectOption(category ? { label: category } : '')
      await dialog.getByRole('button', { name: 'Add', exact: true }).click()
    }
    const closeRails = async () => { if (width < 900 && await page.locator('.workshop-shell').evaluate(el => el.classList.contains('mobile-left-open'))) await page.keyboard.press('Escape') }
    await load()
    if (width < 900) await page.getByRole('button', { name: 'Open prompts', exact: true }).click()
    const manageButton = page.getByRole('button', { name: 'Manage prompts', exact: true })
    await manageButton.scrollIntoViewIfNeeded()
    const buttonBounds = await manageButton.boundingBox()
    const iconBounds = await manageButton.locator('svg').boundingBox()
    assert.ok(Math.abs(buttonBounds.x + buttonBounds.width / 2 - iconBounds.x - iconBounds.width / 2) <= 0.5)
    assert.ok(Math.abs(buttonBounds.y + buttonBounds.height / 2 - iconBounds.y - iconBounds.height / 2) <= 0.5)
    assert.equal(await manageButton.locator('svg').getAttribute('aria-hidden'), 'true')
    if (process.env.WORKSHOP_SCREENSHOT_DIR) await manageButton.screenshot({ path: `${process.env.WORKSHOP_SCREENSHOT_DIR}/manage-plus-${width}.png` })
    await open()
    assert.equal(await dialog.getByRole('searchbox').evaluate(el => el === document.activeElement), true)
    const bounds = await dialog.boundingBox()
    assert.ok(bounds.y >= (width < 900 ? 54 : 0))
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width)
    const addGroup = await dialog.getByRole('group', { name: 'Add items', exact: true }).boundingBox()
    const addBoxes = await Promise.all(['prompt', 'marker', 'category'].map(kind => dialog.getByRole('button', { name: `Add ${kind}`, exact: true }).boundingBox()))
    assert.ok(Math.abs(addBoxes[0].x - addGroup.x) <= 1)
    assert.ok(Math.abs(addBoxes[2].x + addBoxes[2].width - addGroup.x - addGroup.width) <= 1)
    assert.ok(Math.max(...addBoxes.map(box => box.width)) - Math.min(...addBoxes.map(box => box.width)) <= 1)
    assert.ok((await dialog.locator('[data-manage="root-drop"]').boundingBox()).height <= 30)
    assert.equal(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), true)
    await dialog.getByRole('button', { name: 'Done', exact: true }).focus()
    await page.keyboard.press('Shift+Tab')
    assert.equal(await dialog.getByRole('button', { name: 'Cancel', exact: true }).evaluate(el => el === document.activeElement), true)
    const ids = await dialog.locator('[id]').evaluateAll(elements => elements.map(el => el.id))
    assert.equal(new Set(ids).size, ids.length)
    assert.equal(await dialog.locator('button').evaluateAll(buttons => buttons.every(button => (button.getAttribute('aria-label') || button.textContent).trim().length > 0)), true)
    await dialog.getByRole('button', { name: 'Reorder one', exact: true }).press('Enter')
    assert.equal(await dialog.getByRole('button', { name: 'Move down one', exact: true }).evaluate(el => el === document.activeElement), true)
    // A whole dialog session is cancellable, including category removal.
    await add('category', 'Planning')
    await add('prompt', 'New draft', 'Planning')
    await dialog.getByRole('button', { name: 'Add marker', exact: true }).click()
    await dialog.getByRole('combobox', { name: 'Marker type', exact: true }).selectOption('chat_history')
    await dialog.getByRole('combobox', { name: 'Category', exact: true }).selectOption({ label: 'Planning' })
    await dialog.getByRole('button', { name: 'Add', exact: true }).click()
    await choose('Planning')
    await dialog.getByRole('button', { name: 'Move up Planning', exact: true }).click()
    assert.deepEqual(await titles(), ['one', 'two', 'Planning', 'New draft', 'Chat History', 'other'])
    await choose('New draft')
    if (width > 900) {
      const up = await dialog.getByRole('button', { name: 'Move up New draft', exact: true }).boundingBox()
      const destination = await dialog.getByRole('combobox', { name: 'Move to', exact: true }).boundingBox()
      assert.ok(Math.abs(up.y + up.height / 2 - destination.y - destination.height / 2) <= 1)
    }
    await dialog.getByRole('combobox', { name: 'Move to', exact: true }).selectOption('')
    await dialog.getByRole('button', { name: 'Move', exact: true }).click()
    await dialog.getByRole('button', { name: 'Move up New draft', exact: true }).click()
    assert.deepEqual(await titles(), ['one', 'two', 'Planning', 'Chat History', 'New draft', 'other'])
    if (width > 900) {
      const target = dialog.locator('[data-manage-id="other"]')
      const box = await target.boundingBox()
      await dialog.getByRole('button', { name: 'Reorder one', exact: true }).dragTo(target, { targetPosition: { x: box.width / 2, y: box.height - 3 } })
      assert.deepEqual(await titles(), ['two', 'Planning', 'Chat History', 'New draft', 'other', 'one'])
    }
    await choose('Planning')
    await dialog.getByRole('button', { name: 'Delete Planning', exact: true }).click()
    assert.equal(await dialog.getByRole('button', { name: 'Delete Planning', exact: true }).getAttribute('aria-expanded'), 'true')
    await dialog.getByRole('button', { name: 'Keep prompts ungrouped', exact: true }).click()
    assert.equal(await dialog.getByRole('button', { name: 'Select Chat History', exact: true }).count(), 1)
    await choose('Chat History')
    await dialog.getByRole('button', { name: 'Delete Chat History', exact: true }).click()
    await dialog.getByRole('button', { name: 'Delete item', exact: true }).click()
    await add('category', 'Remove category')
    await add('prompt', 'Remove child', 'Remove category')
    await choose('Remove category')
    await dialog.getByRole('button', { name: 'Delete Remove category', exact: true }).click()
    await dialog.getByRole('button', { name: 'Delete category and prompts', exact: true }).click()
    assert.equal(await dialog.getByRole('button', { name: 'Select Remove child', exact: true }).count(), 0)
    const moveOrder = (await titles()).filter(name => ['one', 'two', 'other'].includes(name))
    await add('category', 'Bulk destination')
    // Checked order differs from preset order; hidden selections survive search.
    await dialog.getByRole('checkbox', { name: 'Include two in move', exact: true }).check()
    await dialog.getByRole('checkbox', { name: 'Include one in move', exact: true }).focus()
    await page.keyboard.press('Space')
    await dialog.getByRole('searchbox').fill('other')
    await dialog.getByRole('checkbox', { name: 'Select visible prompts', exact: true }).check()
    assert.match(await dialog.getByRole('region', { name: 'Selected item', exact: true }).textContent(), /3 prompts selected/)
    await dialog.getByRole('searchbox').fill('')
    assert.equal(await dialog.getByRole('checkbox', { name: 'Select visible prompts', exact: true }).evaluate(el => el.indeterminate), true)
    assert.equal(await dialog.getByRole('button', { name: 'Move up one', exact: true }).count(), 0)
    await dialog.getByRole('combobox', { name: 'Move to', exact: true }).selectOption({ label: 'Bulk destination' })
    await dialog.getByRole('button', { name: 'Move selected', exact: true }).click()
    assert.deepEqual((await titles()).slice(-3), moveOrder)
    assert.equal(await page.evaluate(() => window.writes), 0)
    assert.equal(await dialog.getByRole('checkbox', { name: 'Include one in move', exact: true }).isChecked(), true)
    await dialog.getByRole('button', { name: 'Clear selection', exact: true }).click()
    assert.equal(await dialog.getByRole('checkbox', { name: 'Include one in move', exact: true }).isChecked(), false)
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal(await page.evaluate(() => window.writes), 0)
    await open()
    assert.deepEqual(await titles(), ['one', 'two', 'other'])
    await dialog.getByRole('searchbox').press('Escape')
    assert.equal(await dialog.count(), 0)
    assert.equal(await page.getByRole('button', { name: 'Manage prompts', exact: true }).evaluate(el => el === document.activeElement), true)
    // An unsaved native draft survives organization and is included in final Apply.
    await page.locator('[data-role="prompt-list"] [data-block-id="one"]').click()
    await page.getByLabel('Native content').fill('Retained editor draft')
    await open()
    await add('category', 'Working category')
    await add('prompt', 'Fresh prompt', 'Working category')
    if (process.env.WORKSHOP_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.WORKSHOP_SCREENSHOT_DIR}/prompt-manager-${width}.png` })
    await dialog.getByRole('button', { name: 'Done', exact: true }).click()
    assert.equal(await page.evaluate(() => window.writes), 0)
    await closeRails()
    await page.getByLabel('Native content').fill('New prompt content')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await open()
    assert.deepEqual(await titles(), ['one', 'two', 'other', 'Working category', 'Fresh prompt'])
    await dialog.getByRole('searchbox').fill('Fresh')
    assert.deepEqual(await titles(), ['Working category', 'Fresh prompt'])
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await closeRails()
    await page.evaluate(() => { window.backupFailure = true })
    await page.getByRole('button', { name: 'Apply changes', exact: true }).click()
    assert.equal(await page.evaluate(() => window.writes), 0)
    await page.evaluate(() => { window.backupFailure = false })
    await page.getByRole('button', { name: 'Apply changes', exact: true }).click()
    assert.equal(await page.evaluate(() => window.writes), 1)
    const snapshot = await page.evaluate(() => window.snapshot())
    assert.equal(snapshot.blocks[0].content, 'Retained editor draft')
    assert.equal(snapshot.blocks.at(-1).content, 'New prompt content')
    assert.equal(snapshot.blocks.at(-1).group, snapshot.blocks.at(-2).id)
    const backups = await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('backup:')).map(key => JSON.parse(JSON.parse(localStorage.getItem(key)).text)))
    assert.ok(backups.some(backup => backup.kind === 'before-apply' && backup.preset.blocks.length === 3 && backup.preset.blocks[0].content === '{{var::missing_one}}'))
    // Both a stale organizer and a host change after local staging fail without writes.
    await open(); await add('prompt', 'Stale prompt', '')
    await page.evaluate(() => window.external('other'))
    await dialog.getByRole('button', { name: 'Done', exact: true }).click()
    assert.match(await dialog.getByRole('alert').textContent(), /changed/)
    assert.equal(await page.evaluate(() => window.writes), 1)
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await open(); await add('prompt', 'Conflicting prompt', '')
    await dialog.getByRole('button', { name: 'Done', exact: true }).click()
    await page.evaluate(() => window.external('two'))
    await closeRails()
    await page.getByRole('button', { name: 'Apply changes', exact: true }).click()
    assert.equal(await page.evaluate(() => window.writes), 1)
    assert.equal(await page.evaluate(() => window.snapshot().blocks.some(b => b.name === 'Conflicting prompt')), false)
    await page.getByRole('button', { name: 'Discard drafts', exact: true }).click()
    await open()
    assert.equal(await dialog.getByRole('button', { name: 'Select Conflicting prompt', exact: true }).count(), 0)
    await page.evaluate(() => window.disposeWorkshop())
    assert.equal(await dialog.count(), 0)
    await page.evaluate(() => { window.disposeWorkshop = window.mountWorkshop() })
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    await open()
    assert.equal(await dialog.getByRole('searchbox').inputValue(), '')
    await dialog.getByRole('checkbox', { name: 'Include other in move', exact: true }).check()
    await dialog.getByRole('checkbox', { name: 'Include two in move', exact: true }).check()
    await dialog.getByRole('combobox', { name: 'Move to', exact: true }).selectOption({ label: 'Working category' })
    if (process.env.WORKSHOP_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.WORKSHOP_SCREENSHOT_DIR}/prompt-manager-bulk-${width}.png` })
    await dialog.getByRole('button', { name: 'Move selected', exact: true }).click()
    await dialog.getByRole('button', { name: 'Done', exact: true }).click()
    await closeRails()
    await page.getByRole('button', { name: 'Apply changes', exact: true }).click()
    const movedSnapshot = await page.evaluate(() => window.snapshot())
    const categoryId = movedSnapshot.blocks.find(block => block.name === 'Working category').id
    assert.deepEqual(movedSnapshot.blocks.slice(-2).map(block => [block.name, block.group]), [['two', categoryId], ['other', categoryId]])
    assert.equal(await page.evaluate(() => window.writes), 2)
    // Large lists, creation forms, and deletion choices remain usable on a
    // notched phone with a shorter viewport. No personal data is involved.
    await page.goto(`http://127.0.0.1:${server.address().port}`)
    await page.evaluate(() => window.populateManagerFixture())
    if (width < 900) await page.setViewportSize({ width, height: 740 })
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    await open()
    assert.equal(await dialog.getByRole('listitem').count(), 143)
    await dialog.getByRole('button', { name: 'Select Prompt 1 — a long title for the organization list', exact: true }).click()
    await dialog.getByRole('button', { name: 'Move down Prompt 1 — a long title for the organization list', exact: true }).press('Enter')
    await dialog.getByRole('button', { name: 'Add marker', exact: true }).click()
    assert.equal(await dialog.getByRole('button', { name: 'Add marker', exact: true }).getAttribute('aria-expanded'), 'true')
    assert.equal(await dialog.getByRole('combobox', { name: 'Marker type', exact: true }).isVisible(), true)
    await dialog.getByRole('button', { name: 'Cancel add', exact: true }).click()
    await dialog.getByRole('button', { name: 'Delete Prompt 1 — a long title for the organization list', exact: true }).click()
    await dialog.getByRole('button', { name: 'Cancel deletion', exact: true }).click()
    assert.equal(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), true)
    const moveBounds = await dialog.getByRole('combobox', { name: 'Move to', exact: true }).boundingBox()
    assert.ok(moveBounds.width > 100)
    await dialog.getByRole('button', { name: 'Done', exact: true }).scrollIntoViewIfNeeded()
    const doneBounds = await dialog.getByRole('button', { name: 'Done', exact: true }).boundingBox()
    assert.ok(doneBounds.y + doneBounds.height <= page.viewportSize().height)
    if (process.env.WORKSHOP_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.WORKSHOP_SCREENSHOT_DIR}/prompt-manager-large-${width}.png` })
    assert.deepEqual(errors, [])
    console.log(`PASS Manage prompts ${width}px: add, delete choices, order, local drafts, backup, conflict, focus, safe top, teardown/remount${width > 900 ? ', mouse drag' : ', touch-friendly move controls'}`)
    await page.close()
  }
} catch (error) {
  const page = browser.contexts()[0]?.pages()[0]
  if (page) console.error((await page.locator('body').ariaSnapshot()).slice(-5000))
  throw error
} finally { await browser.close(); server.close() }
