import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createServer } from 'node:http'
import { pathToFileURL } from 'node:url'
import { join } from 'node:path'
import { fixture } from './workshop-fixture.mjs'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
const frontend = await readFile(new URL('../dist/frontend.js', import.meta.url))
const backend = await readFile(new URL('../dist/backend.js', import.meta.url))
const server = createServer((req, res) => { res.setHeader('Content-Type', req.url.endsWith('.js') ? 'text/javascript' : 'text/html'); res.end(req.url === '/frontend.js' ? frontend : req.url === '/backend.js' ? backend : fixture) })
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const browser = await chromium.launch({ headless: true })
try {
  for (const width of [1440, 390]) {
    const page = await browser.newPage({ viewport: { width, height: width < 900 ? 844 : 900 }, permissions: ['clipboard-read', 'clipboard-write'] })
    await page.route('**/api/v1/connections/*/models', route => route.fulfill({ json: { models: ['Fixture model'] } }))
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    await page.goto(`http://127.0.0.1:${server.address().port}`)
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    if (width < 900) await page.getByRole('button', { name: 'Open prompts', exact: true }).click()
    await page.locator('[data-block-id="one"]').click()
    await page.getByRole('textbox', { name: 'Native content', exact: true }).fill('Unsynced primary draft')
    await page.getByRole('button', { name: 'Reference', exact: true }).click()
    const view = page.getByRole('region', { name: 'Reference preset', exact: true })
    const picker = view.getByLabel('Reference preset', { exact: true })
    await picker.locator('option[value="reference"]').waitFor({ state: 'attached' })
    assert.equal(await picker.locator('option[value="fixture"]').count(), 0)
    await picker.selectOption('reference')
    await view.getByRole('button', { name: 'Reference first', exact: true }).click()
    const content = view.getByRole('textbox', { name: 'Read-only prompt content', exact: true })
    const literal = '{{setchatvar::probe::true}}<img src=x onerror="window.referenceUnsafe=true">'
    assert.equal(await content.inputValue(), literal)
    assert.equal(await content.getAttribute('readonly'), '')
    await content.focus(); await page.keyboard.press('Control+A'); await page.keyboard.type('Cannot edit')
    assert.equal(await content.inputValue(), literal)
    await view.getByRole('button', { name: 'Copy reference prompt', exact: true }).press('Enter')
    await view.getByRole('status').filter({ hasText: 'Reference prompt copied.' }).waitFor()
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), literal)
    await page.evaluate(() => { window.referenceClipboard = navigator.clipboard; Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined }) })
    await view.getByRole('button', { name: 'Copy reference prompt', exact: true }).click()
    await view.getByRole('status').filter({ hasText: 'Clipboard unavailable.' }).waitFor()
    assert.equal(await content.evaluate(el => el === document.activeElement && el.selectionStart === 0 && el.selectionEnd === el.value.length), true)
    await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: window.referenceClipboard }))
    await view.getByRole('button', { name: 'Copy reference prompt', exact: true }).click()
    await view.getByRole('status').filter({ hasText: 'Reference prompt copied.' }).waitFor()
    assert.equal(await view.locator('img,script').count(), 0)
    assert.equal(await page.evaluate(() => window.referenceUnsafe), undefined)
    await view.locator('summary').filter({ hasText: 'Reference section' }).press('Enter')
    assert.equal(await view.getByRole('button', { name: 'Reference second', exact: true }).isVisible(), false)
    await view.getByRole('searchbox', { name: 'Search reference prompts', exact: true }).fill('Second reference content')
    await view.getByRole('button', { name: 'Reference second', exact: true }).click()
    assert.equal(await content.inputValue(), 'Second reference content')
    await page.getByRole('button', { name: 'Stack', exact: true }).click()
    assert.equal(await view.isVisible(), false)
    await page.getByRole('button', { name: 'Reference', exact: true }).press('Enter')
    assert.equal(await content.inputValue(), 'Second reference content')
    assert.equal(await page.getByRole('textbox', { name: 'Native content', exact: true }).inputValue(), 'Unsynced primary draft')
    await page.getByRole('button', { name: 'Hide', exact: true }).click()
    assert.equal(await view.isVisible(), false)
    await page.getByRole('button', { name: 'Show', exact: true }).click()
    assert.equal(await content.inputValue(), 'Second reference content')
    await page.getByRole('button', { name: 'Move preview to the side', exact: true }).click()
    // Bottom docking on phones shares the host's safe-area layout.
    await page.waitForFunction(() => { const r = document.querySelector('.workshop-reference').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth })
    for (const locator of [view, picker, content, page.getByRole('button', { name: 'Close Workshop', exact: true })]) {
      const box = await locator.boundingBox()
      assert.ok(box && box.width > 0 && box.height > 0 && box.x >= 0 && box.x + box.width <= width + 1 && box.y >= (width < 900 ? 54 : 0), JSON.stringify(box))
    }
    if (width < 900) assert.ok((await view.boundingBox()).height >= 300)
    if (process.env.SANDBOX_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.SANDBOX_SCREENSHOT_DIR, `workshop-reference-${width}.png`) })
    await page.evaluate(() => { window.activeChat = 'controlled-chat' })
    await page.waitForTimeout(1350)
    assert.equal(await page.evaluate(() => window.frontendRequests.filter(type => type === 'workshop:assemble').length), 0)
    await page.evaluate(() => { window.activeChat = null })
    // Late reads cannot replace a more recently selected preset.
    await page.evaluate(() => { window.referenceDelay = 'reference' })
    await picker.selectOption('alternate')
    await view.getByRole('button', { name: 'alt', exact: true }).waitFor()
    await picker.selectOption('reference')
    await page.waitForFunction(() => typeof window.releaseReference === 'function')
    await picker.selectOption('alternate')
    await view.getByRole('button', { name: 'alt', exact: true }).click()
    await page.evaluate(() => { window.releaseReference(); window.referenceDelay = null })
    await page.waitForTimeout(100)
    assert.equal(await content.inputValue(), 'Alternate content')
    await page.evaluate(() => { window.referencePresets = window.referencePresets.filter(p => p.id !== 'alternate') })
    await page.getByRole('button', { name: 'Refresh reference preset', exact: true }).click()
    await view.getByRole('status').filter({ hasText: 'Choose a second preset' }).waitFor()
    assert.equal(await content.inputValue(), '')
    await page.evaluate(() => { window.referenceListFailure = true })
    await view.getByRole('button', { name: 'Refresh reference presets', exact: true }).click()
    await view.getByRole('status').filter({ hasText: 'Reference list unavailable' }).waitFor()
    await page.evaluate(() => { window.referenceListFailure = false })
    await view.getByRole('button', { name: 'Refresh reference presets', exact: true }).click()
    await view.getByRole('status').filter({ hasText: 'Choose a second preset' }).waitFor()
    // Agent reparenting retains the same independent reference view.
    await page.getByRole('button', { name: 'Agent', exact: true }).click()
    await picker.selectOption('reference')
    await view.getByRole('button', { name: 'Reference first', exact: true }).click()
    assert.equal(await content.inputValue(), literal)
    assert.equal(await page.evaluate(() => window.writes), 0)
    assert.equal(await page.evaluate(() => window.snapshot().blocks[0].content), '{{var::missing_one}}')
    assert.ok((await page.evaluate(() => window.referenceReads)).every(read => read.at(-1) === 'fixture-user'))
    await picker.selectOption('')
    await page.evaluate(() => { window.referenceDelay = 'reference'; window.releaseReference = null })
    await picker.selectOption('reference')
    await page.waitForFunction(() => typeof window.releaseReference === 'function')
    await page.evaluate(() => { window.disposeWorkshop(); window.releaseReference(); window.referenceDelay = null })
    await view.waitFor({ state: 'detached' })
    await page.evaluate(() => { window.disposeWorkshop = window.mountWorkshop() })
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    await page.getByRole('button', { name: 'Reference', exact: true }).click()
    const newPicker = page.getByRole('region', { name: 'Reference preset', exact: true }).getByLabel('Reference preset', { exact: true })
    await newPicker.locator('option[value="reference"]').waitFor({ state: 'attached' })
    assert.equal(await newPicker.inputValue(), '')
    assert.deepEqual(errors, [])
    console.log(`PASS read-only reference: copy, sections, search, draft isolation, docking, stale reads, missing presets, agent mode and remount: ${width}px`)
    await page.close()
  }
} finally { await browser.close(); server.close() }
