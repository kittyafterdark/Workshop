import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createServer } from 'node:http'
import { pathToFileURL } from 'node:url'
import { fixture } from './workshop-fixture.mjs'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
const bundle = await readFile(new URL('../dist/frontend.js', import.meta.url))
const backend = await readFile(new URL('../dist/backend.js', import.meta.url))
const server = createServer((req, res) => {
  res.setHeader('Content-Type', req.url.endsWith('.js') ? 'text/javascript' : 'text/html')
  res.end(req.url === '/frontend.js' ? bundle : req.url === '/backend.js' ? backend : fixture)
})
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) })
try {
  for (const width of [1440, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`http://127.0.0.1:${server.address().port}`)
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    const launch = page.getByRole('button', { name: 'Find and replace', exact: true })
    await launch.press('Enter')
    const dialog = page.getByRole('dialog', { name: 'Preset find and replace', exact: true })
    const find = dialog.getByLabel('Find', { exact: true })
    assert.equal(await find.evaluate(el => el === document.activeElement), true)
    assert.equal(await dialog.getByRole('button', { name: 'Replace all', exact: true }).isDisabled(), true)
    const bounds = await dialog.boundingBox()
    assert.ok(bounds.y >= (width < 900 ? 54 : 0))
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width)
    await find.fill('missing_')
    await dialog.getByLabel('Replace with', { exact: true }).fill('found_')
    assert.equal(await dialog.getByRole('listitem').count(), 2)
    await dialog.locator('summary').first().click()
    assert.match(await dialog.locator('pre').nth(1).textContent(), /found_one/)
    assert.equal(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), true)
    if (process.env.WORKSHOP_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.WORKSHOP_SCREENSHOT_DIR}/find-replace-${width}.png` })
    await find.press('Escape')
    assert.equal(await dialog.count(), 0)
    assert.equal(await launch.evaluate(el => el === document.activeElement), true)
    assert.equal(await page.evaluate(() => window.writes), 0)
    await launch.click()
    await find.fill('missing_')
    await dialog.getByLabel('Replace with', { exact: true }).fill('found_')
    // Reject a stale preview before any local replacement is staged.
    await page.evaluate(() => window.external('one'))
    await dialog.getByRole('button', { name: 'Replace all', exact: true }).click()
    assert.match(await dialog.getByRole('alert').textContent(), /changed/)
    assert.equal(await page.evaluate(() => window.writes), 0)
    await dialog.getByRole('button', { name: 'Refresh preview' }).click()
    assert.equal(await dialog.getByRole('listitem').count(), 1)
    await dialog.getByRole('button', { name: 'Replace all', exact: true }).click()
    assert.equal(await page.evaluate(() => window.writes), 0)
    await page.evaluate(() => { window.external('other'); window.backupFailure = true })
    await page.locator('[data-action="apply-drafts"]').click()
    assert.match(await page.getByRole('alert').textContent(), /Backup storage/)
    assert.equal(await page.evaluate(() => window.writes), 0)
    await page.evaluate(() => { window.backupFailure = false })
    await page.locator('[data-action="apply-drafts"]').click()
    assert.deepEqual(await page.evaluate(() => window.snapshot().blocks.map(block => block.content)), ['external change', '{{var::found_two}}', 'external change'])
    assert.equal(await page.evaluate(() => window.writes), 1)
    await page.getByRole('button', { name: 'Preset backups', exact: true }).click()
    await page.getByText('Before Find and Replace', { exact: false }).waitFor()
    const backups = await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('backup:')).map(key => JSON.parse(JSON.parse(localStorage.getItem(key)).text)))
    assert.equal(backups.length, 1)
    assert.equal(backups[0].kind, 'before-find-replace')
    assert.equal(backups[0].preset.blocks[1].content, '{{var::missing_two}}')
    await page.locator('.workshop-review').getByRole('button', { name: 'Close', exact: true }).click()
    if (width < 900) await page.getByRole('button', { name: 'Open prompts', exact: true }).click()
    await page.locator('.workshop-row[data-block-id="two"]').click()
    assert.equal(await launch.isVisible(), false)
    await page.locator('[data-role="editor-mount"]').getByRole('button', { name: 'Save', exact: true }).click()
    assert.equal(await launch.isVisible(), true)
    await launch.click()
    await find.fill('found_')
    // An empty replacement removes text and Cancel leaves the preset untouched.
    assert.equal(await dialog.getByRole('listitem').count(), 1)
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal(await page.evaluate(() => window.writes), 1)
    await launch.click()
    await page.evaluate(() => window.disposeWorkshop())
    assert.equal(await dialog.count(), 0)
    await page.evaluate(() => { window.disposeWorkshop = window.mountWorkshop() })
    await page.getByRole('button', { name: 'Open Workshop', exact: true }).click()
    await launch.click()
    assert.equal(await find.inputValue(), '')
    assert.deepEqual(errors, [])
    console.log(`PASS preset find/replace: preview, cancellation, stale preview, Apply, named backup, toolbar, safe top and remount: ${width}px`)
    await page.close()
  }
} finally { await browser.close(); server.close() }
